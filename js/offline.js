/**
 * Оффлайн: что и как кеширует сервис-воркер.
 *
 * Здесь нет ничего, что касается service worker API: только вычисление имён и
 * адресов. Причина в том, что самое хрупкое в оффлайне — это не сам воркер, а
 * адреса: стоит собрать `js/main.js` без `?v=`, и кеш молча начнёт отдавать
 * прошлую сборку, а это ровно тот баг, над которым семь коммитов подряд
 * возились с MAX WebView (tools/cache-recovery.mjs). Поэтому адреса
 * вычисляются здесь, покрываются unit-тестами, а sw.js получает готовый список.
 *
 * Ключевая идея: неизменяемость уже обеспечена механизмом `?v=`, который
 * threaded'ится через весь граф модулей. Поэтому прекэшить версионированные
 * адреса безопасно — они физически не могут совпасть с прошлой сборкой. Шелл
 * (index.html) и css/ иконки версионирования не имеют, и их нельзя отдавать
 * из кеша вслепую: воркер обновляется на каждом запуске, поэтому имя кеша
 * меняется вместе с ревизией.
 */

/** Модули графа шелла. Порядок не важен, список обязан совпадать с main.js. */
export const SHELL_MODULES = [
  'bootstrap',
  'launch-router',
  'quizzzz-routing',
  'bridge',
  'main',
  'track',
  'web-vitals',
  'share',
  'duel',
  'daily',
  'engagement',
  'progress',
  'ui-state',
  'games',
  // Сам модуль оффлайна тоже в графе: main.js тянет его ради вычисления
  // адреса регистрации, и без него в кеше оказывается весь остальной шелл, но
  // не он — падала бы вся загрузка.
  'offline',
];

/** Статика шелла без версии в адресе. */
export const SHELL_ASSETS = [
  'css/hub.css',
  'css/polish.css',
  'assets/icons.svg',
  // Импортируется из js/web-vitals.js обычным статическим импортом, то есть
  // без ?v=. Без него в кеше окажется сам модуль, но не его зависимость, и
  // оффлайн развалится на первой же загрузке метрик.
  'js/vendor/web-vitals/web-vitals.attribution.js',
];

/**
 * Имя кеша, привязанное к ревизии.
 *
 * Ревизия входит в имя намеренно: новая сборка порождает новое имя, и старый
 * кеш удаляется в activate. Если бы имя не менялось, новая сборка продолжила
 * бы отдавать файлы прошлой.
 */
export function swCacheName(revision) {
  return `hub-${String(revision || 'dev').replace(/[^A-Za-z0-9._-]/g, '-')}`;
}

/**
 * Адрес самого воркера: ревизия едет в query, откуда её читает сам sw.js.
 *
 * База нормализуется, потому что её приходится вычислять: main.js лежит в js/,
 * поэтому корень приложения — это `../` от него, и наивная склейка дала бы
 * `/js//sw.js`. Лишний слэш в адресе воркера означает отказ регистрации.
 */
export function swRegisterUrl(revision, base = '.') {
  return `${String(base).replace(/\/+$/, '')}/sw.js?v=${encodeURIComponent(String(revision || 'dev'))}`;
}

/**
 * Список адресов для прекэша.
 *
 * Пути относительные намеренно: в production Caddy отдаёт хаб под `/hub/` и
 * срезает префикс, так что абсолютный `/js/main.js` воркеру не подошёл бы.
 * Относительные адреса разрешаются от scope воркера и одинаково работают и в
 * dev на корне, и под `/hub/`.
 */
export function swPrecacheList(revision) {
  const v = `?v=${encodeURIComponent(String(revision || 'dev'))}`;
  return [
    'index.html',
    // runtime-config.js кладётся в кеш, хотя отдаётся no-store. Это не
    // противоречие: воркер сначала всегда идёт в сеть и обновляет копию, и
    // только если сети нет — отдаёт последнюю. Без него оффлайн невозможен в
    // принципе: без ревизии из конфига не грузится ни один модуль шелла.
    'runtime-config.js',
    ...SHELL_MODULES.map((name) => `js/${name}.js${v}`),
    ...SHELL_ASSETS,
  ];
}

/**
 * Что воркер не должен трогать никогда.
 *
 * Только аналитика и внешние адреса. runtime-config.js здесь отсутствует
 * намеренно: см. swPrecacheList — он требует network-first с откатом, а не
 * обхода, и вынесен в отдельную ветку fetch.
 */
export function isBypassed(url) {
  const path = typeof url === 'string' ? url : url.url;
  if (/^https?:/i.test(path) && !/^https?:\/\/(127\.0\.0\.1|localhost)/i.test(path)) return true;
  if (path.includes('/hub-api/')) return true;
  if (path.includes('st.max.ru')) return true;
  return false;
}

/**
 * Версионированный адрес того же ресурса.
 *
 * Нужна для внутримодульных статических импортов: `?v=` навешивается только на
 * верхнеуровневые динамические импорты в main.js, а `import ... from './x.js'`
 * внутри модуля остаётся без него. Из-за этого оффлайн ломался на
 * `js/daily.js`, который тянет engagement.js: сети нет, неверсионированного
 * адреса в кеше нет, и весь граф падал.
 *
 * Откат берёт ту же самую сборку из кеша с ревизией, а не «что-нибудь
 * похожее», поэтому подставлять его безопасно.
 */
export function versionedFallback(pathname, revision) {
  const clean = String(pathname).replace(/[?&]v=[^&]*/, '');
  return `${clean}?v=${encodeURIComponent(String(revision || 'dev'))}`;
}

/**
 * Конфигурация сборки: требует свежести, но обязана выживать без сети.
 *
 * Отдельная ветка, потому что требования противоположны остальным: cache-first
 * здесь означал бы вечную старую ревизию, а skip («никогда не кешировать») —
 * означал бы, что оффлайн не включается никогда.
 */
export function isRuntimeConfig(url) {
  const path = typeof url === 'string' ? url : url.url;
  return path.includes('runtime-config.js');
}

/**
 * Версионирован ли адрес.
 *
 * `?v=` означает, что содержимое по этому адресу физически не изменится:
 * новая ревизия порождает новый адрес. Такие ответы можно отдавать из кеша
 * безусловно. Всё остальное — нет.
 */
export function isVersioned(url) {
  const path = typeof url === 'string' ? url : url.url;
  return /[?&]v=/.test(path);
}
