/**
 * Детерминированная случайность для «пазла дня».
 *
 * Хаб уже умеет открывать игру с `?seed=YYYY-MM-DD` (js/main.js), но до сих пор
 * это работало только для сапёра и викторины: алгоритм жил текстом внутри
 * tools/vendor.mjs и текстовыми правками подставлялся в их script.js. Остальные
 * десять игр игнорировали seed, хотя три из них помечены в манифесте как daily.
 * Чтобы сделать пазл дня настоящим, нужен был один шим на все игры.
 *
 * Шим подменяет Math.random, а не вводит новую функцию. Иначе пришлось бы
 * править около тридцати мест вызова в чужих исходниках, и любая новая игра
 * снова оказалась бы недетерминированной. Здесь правится одна строка подключения
 * в games/<id>/index.html, а всё остальное работает само.
 *
 * Без `?seed` Math.random остаётся нетронутым: обычный заход игрока должен
 * быть по-настоящему случайным, детерминизм нужен только для daily.
 *
 * Алгоритм (hash + mulberry32) перенесён из tools/vendor.mjs без изменений, и
 * это осознанно: иначе раскладки за прошлые доли разъехались бы у игроков,
 * уже видевших сегодняшний пазл. Совместимость закреплена тестами.
 */
(function () {
'use strict';

/**
 * Строка в беззнаковое 32-битное число.
 *
 * Константы взяты из SHA-2: 1779033703 = 0x6A09E667, 3432918353 = 0xCC9E2D51.
 * Поворот на 13 бит влево вместо сложения нужен, чтобы короткие seed вида
 * «2026-09-06» не вырождались в почти одинаковые состояния.
 */
function hashString(value) {
  let h = 1779033703 ^ value.length;
  for (let i = 0; i < value.length; i++) {
    h = Math.imul(h ^ value.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return h >>> 0;
}

/**
 * Генератор из seed-строки: mulberry32.
 *
 * Возвращает обычную функцию без состояния наружу, поэтому её нельзя случайно
 * сдвинуть, вызвав дважды: состояние живёт в замыкании.
 */
function makeSeededRandom(seed) {
  let state = hashString(String(seed));
  return function seededRandom() {
    let t = (state += 0x6D2B79F5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Читает seed из строки запроса. Пустая строка — «seed не задан». */
function readSeed(search) {
  if (!search) return '';
  try {
    return new URLSearchParams(search).get('seed') || '';
  } catch {
    // Файл подключается до скрипта каждой игры, поэтому исключение здесь
    // уронило бы загрузку целиком. Отсутствие seed безопаснее падения.
    return '';
  }
}

/**
 * Подменяет Math.random на детерминированный, если в адресе есть ?seed.
 *
 * Математика передаётся аргументом намеренно: так вызывающий (и тест) решает,
 * что подменять, а функция не достаётся до глобального состояния сама.
 * Возвращает исходный random, если подмена состоялась, иначе null — так
 * вызывающий может и откатить подмену, и понять, что её не было.
 */
function installSeedRandom(search, math) {
  const seed = readSeed(search);
  if (!seed) return null;
  const original = math.random;
  math.random = makeSeededRandom(seed);
  return original;
}

const api = { hashString, makeSeededRandom, readSeed, installSeedRandom };
globalThis.__hubRng = api;

// В node/vm-средех location нет: подменять Math.random глобально нельзя, и
// вызывающий (tools/daily.mjs) ставит seed сам. Поэтому автозапуск только при
// наличии location.
if (typeof location !== 'undefined') installSeedRandom(location.search, Math);
})();
